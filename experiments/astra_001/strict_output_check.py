"""Strict streaming validator for aligned outputs; keeps only raw ID sets, not all candidates.

Both files generated by ASTRA are deliberately in source-file order. This checker
verifies that stronger invariant and fails on any mismatch rather than silently
reordering. General challenge submissions may use a different valid row order.
"""
import argparse,csv,json,itertools
from pathlib import Path

def run(matching,candidate,testdir):
 valid=set()
 for source in [2,3]:
  with open(testdir/f'test_source{source}.tsv') as f:
   for row in csv.DictReader(f,delimiter='\t',quoting=csv.QUOTE_NONE):
    eid=row['entity_id'];assert eid.startswith(f'S{source}-'),f'Wrong source ID: {eid}';assert eid not in valid,f'Duplicate raw ID: {eid}';valid.add(eid)
 stats={'rows':0,'predicted_matches':0,'candidate_pairs':0,'empty_predictions':0};seen=set()
 with open(matching) as mf,open(candidate) as cf,open(testdir/'test_source1.tsv') as rf:
  assert mf.readline().rstrip('\n')=='source1_entity_id\tmatched_entity_ids','Matching header mismatch'
  assert cf.readline().rstrip('\n')=='source1_entity_id\tcandidate_entity_ids','Candidate header mismatch'
  next(rf)
  for ml,cl,rl in itertools.zip_longest(mf,cf,rf):
   assert ml is not None and cl is not None and rl is not None,'Different row counts'
   m=ml.rstrip('\n').split('\t');c=cl.rstrip('\n').split('\t');rid=rl.split('\t',1)[0]
   assert len(m)==len(c)==2,'Exactly two tab-separated output columns required'
   assert m[0]==c[0]==rid,f'Row order/ID mismatch at {rid}'
   assert rid.startswith('S1-') and rid not in seen,f'Duplicate/invalid S1: {rid}';seen.add(rid)
   ms=m[1].split(',') if m[1] else [];cs=c[1].split(',') if c[1] else [];mset=set(ms);cset=set(cs)
   assert len(ms)==len(mset) and len(cs)==len(cset),f'Duplicate IDs for {rid}'
   assert mset<=cset,f'Match outside candidate set: {rid}'
   assert cset<=valid,f'Unknown/non-S2/S3 candidate IDs for {rid}: {cset-valid}'
   stats['rows']+=1;stats['predicted_matches']+=len(ms);stats['candidate_pairs']+=len(cs);stats['empty_predictions']+=not ms
 stats['validator']='PASS';return stats
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('--matching',type=Path,required=True);p.add_argument('--candidate',type=Path,required=True);p.add_argument('--test-dir',type=Path,required=True);p.add_argument('--report',type=Path);a=p.parse_args();s=run(a.matching,a.candidate,a.test_dir)
 if a.report:a.report.write_text(json.dumps(s,indent=2))
 print(json.dumps(s,indent=2))
